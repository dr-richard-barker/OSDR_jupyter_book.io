# ── Section 4: RadLab data for each mission ────────────────────────────────
cells.append(md(
    "## 4. Fetching radiation data for each mission window",
    "",
    "For each study we query DosTel1 (a DOSTEL detector in the Columbus module) for a",
    "7-day window at the start of the mission, and compute the **mean absorbed dose",
    "rate**, its standard deviation and the ISS's mean altitude.",
    "",
    "> The 7-day window keeps each request short while covering both the background and",
    "> the SAA passes. Values are in **μGy/hr** (1 μGy/hr = 24 μGy/day). If RadLab does",
    "> not answer, the study is reported as unavailable; no cached values are used.",
))

cells.append(code(
    "from datetime import datetime, timedelta",
    "",
    "def parse_date_flex(s):",
    "    \"\"\"Parse dates in multiple formats returned by OSDR API.\"\"\"",
    "    for fmt in ('%m/%d/%Y', '%d-%b-%Y', '%Y-%m-%d', '%m-%d-%Y'):",
    "        try:",
    "            return datetime.strptime(s.strip(), fmt)",
    "        except (ValueError, AttributeError):",
    "            pass",
    "    return None",
    "",
    "def mission_stats(accession, info, window_days=7):",
    "    \"\"\"Fetch RadLab stats for the study window; mean is None if unavailable.\"\"\"",
    "    start_str = info.get('start', '')",
    "    dt_start = parse_date_flex(start_str)",
    "    if dt_start is None:",
    "        return {'mean_uGy_hr': None, 'source': 'no start date'}",
    "",
    "    dt_end = dt_start + timedelta(days=window_days)",
    "    df = radlab_query(",
    "        'DosTel1', 'absorbed_dose_rate',",
    "        dt_start.strftime('%Y-%m-%d'),",
    "        dt_end.strftime('%Y-%m-%d'),",
    "        fields=('altitude',),",
    "    )",
    "    if df is not None and not df.empty:",
    "        return {",
    "            'mean_uGy_hr': round(df['absorbed_dose_rate'].mean(), 2),",
    "            'std_uGy_hr':  round(df['absorbed_dose_rate'].std(),  2),",
    "            'altitude_km': round(df['altitude'].mean(), 1),",
    "            'n': len(df),",
    "            'source': 'live',",
    "        }",
    "    return {'mean_uGy_hr': None, 'source': 'unavailable'}",
    "",
    "# Collect stats",
    "stats = {}",
    "for acc, info in PLANT_STUDIES.items():",
    "    s = mission_stats(acc, info)",
    "    stats[acc] = s",
    "    src = s.get('source', '?')",
    "    mean = s.get('mean_uGy_hr', 'N/A')",
    "    print(f\"{acc}: mean={mean} uGy/hr, sd={s.get('std_uGy_hr')}, \"",
    "          f\"mean altitude={s.get('altitude_km')} km  [{src}]\")",
))

